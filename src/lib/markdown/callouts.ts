export function calloutKind(type: string): Kind {
  return KINDS[type.toLowerCase()] ?? KINDS.note!;
}

export type CalloutHead = {
  type: string;
  /** `-` folds by default, `+` opens by default; either makes it foldable. */
  fold: "-" | "+" | null;
  /** The explicit title, or null for the type's name. */
  title: string | null;
  /** Offset of the marker's `[`, and of the title text, in the line. */
  markerFrom: number;
  titleFrom: number;
};

const HEAD = /^(\s*>\s*)\[!([\w-]+)\]([+-]?)(\s*)(.*)$/;

/** Reads the first line of a blockquote as a callout header, if it is one. */
export function parseCalloutHead(line: string): CalloutHead | null {
  const m = HEAD.exec(line);
  if (!m) return null;
  const [, lead, type, fold, space, title] = m as unknown as [string, string, string, string, string, string];
  const markerFrom = lead.length;
  const titleFrom = markerFrom + type.length + 3 + fold.length + space.length;
  return { type, fold: (fold || null) as CalloutHead["fold"], title: title.trim() || null, markerFrom, titleFrom };
}

export function defaultTitle(type: string): string {
  return type.charAt(0).toUpperCase() + type.slice(1).toLowerCase();
}
